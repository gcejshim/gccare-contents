out = []
for fid, name, bg, typ, desc in REFS:
    im = Image.open(os.path.join(SRC, fid + '.png')).convert('RGB').resize((798, 462), Image.LANCZOS)
    buf = io.BytesIO(); im.save(buf, 'WEBP', quality=82, method=6)
    out.append({'id': fid, 'name': name, 'bg': bg, 'type': typ, 'desc': desc,
                'src': 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode()})

js = '// make_refs.py가 만든 파일 (직접 고치지 않기)\nwindow.REFS = ' + json.dumps(out, ensure_ascii=False) + ';\n'
